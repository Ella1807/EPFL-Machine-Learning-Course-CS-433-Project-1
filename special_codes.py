def recode(x, name2idx, rules=CODEBOOK_RULES):
    """Copy of x with "don't know/refused" codes set to NaN and "none" codes set to 0."""
    x = x.copy()
    for name, r in rules.items():
        if name not in name2idx:          # variable not in this dataset
            continue
        j = name2idx[name]
        x[np.isin(x[:, j], r.get("nan", [])), j] = np.nan
        x[np.isin(x[:, j], r.get("zero", [])), j] = 0
    return x

def convert_units(x, name2idx):
    """Optional: WEIGHT2 -> kg and HEIGHT3 -> cm (both mix imperial/metric; 7777/9999 -> NaN).
    WEIGHT2: 50-999 = pounds, 9000-9998 = 9 + kilograms.
    HEIGHT3: 200-711 = feet/inches (e.g. 504 = 5'04''), 9000-9998 = 9 + centimeters."""
    x = x.copy()
    if "WEIGHT2" in name2idx:
        j = name2idx["WEIGHT2"]; w = x[:, j]
        kg = np.where(w >= 9000, w - 9000, w * 0.45359237)
        x[:, j] = np.where((w == 7777) | (w == 9999), np.nan, kg)
    if "HEIGHT3" in name2idx:
        j = name2idx["HEIGHT3"]; h = x[:, j]
        cm = np.where(h >= 9000, h - 9000, ((h // 100) * 12 + h % 100) * 2.54)
        x[:, j] = np.where((h == 7777) | (h == 9999), np.nan, cm)
    return x
